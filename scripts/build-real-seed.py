"""Build supabase/seed-real.sql from scripts/real-records.json.

Places each record with Nominatim (OpenStreetMap), one request per second as its usage policy asks.
Run: python -I scripts/build-real-seed.py   (from the civic-app folder)
"""
import json, sys, time, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "scripts" / "real-records.json").read_text(encoding="utf-8"))
CACHE_FILE = ROOT / "scripts" / ".geocode-cache.json"
cache = json.loads(CACHE_FILE.read_text(encoding="utf-8")) if CACHE_FILE.exists() else {}
BBOX = (12.70, 79.95, 13.30, 80.36)  # Chennai metropolitan area


def geocode(name):
    if name in cache:
        return cache[name]
    # Settlements only (suburbs, neighbourhoods, villages), bounded to the Chennai area, so "Medavakkam" does not match "Medavakkam Tank Road".
    params = {"q": name, "format": "json", "limit": 1, "countrycodes": "in", "featureType": "settlement",
              "viewbox": f"{BBOX[1]},{BBOX[2]},{BBOX[3]},{BBOX[0]}", "bounded": 1}
    if "," in name:  # a landmark or street with its area: search it as given
        params.pop("featureType")
    q = urllib.parse.urlencode(params)
    req = urllib.request.Request(f"https://nominatim.openstreetmap.org/search?{q}", headers={"User-Agent": "theru-civic-hackathon/1.0"})
    time.sleep(1.1)
    with urllib.request.urlopen(req, timeout=20) as r:
        hits = json.load(r)
    hit = None
    if hits:
        lat, lng = float(hits[0]["lat"]), float(hits[0]["lon"])
        if BBOX[0] <= lat <= BBOX[2] and BBOX[1] <= lng <= BBOX[3]:
            hit = [round(lat, 5), round(lng, 5)]
    if not hit:  # fall back to Photon (also OpenStreetMap), localities and districts only
        pq = urllib.parse.urlencode([("q", name), ("limit", 1), ("bbox", f"{BBOX[1]},{BBOX[0]},{BBOX[3]},{BBOX[2]}"),
                                     ("layer", "locality"), ("layer", "district"), ("layer", "city")])
        with urllib.request.urlopen(urllib.request.Request(f"https://photon.komoot.io/api/?{pq}", headers={"User-Agent": "theru-civic-hackathon/1.0"}), timeout=20) as r:
            feats = json.load(r)["features"]
        if feats:
            lng, lat = feats[0]["geometry"]["coordinates"]
            hit = [round(lat, 5), round(lng, 5)]
    cache[name] = hit
    return hit


def place(names):
    for n in names:
        p = geocode(n)
        if p:
            return p
    return None


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


rows, skipped = [], []


def add(kind, agency, title, area, latlng, radius, starts, ends, source, url):
    lat, lng = latlng
    rows.append(
        f"  ({q(kind)}, {q(agency[:120])}, {q(title[:200])}, {q(area[:300])}, "
        f"st_setsrid(st_makepoint({lng}, {lat}), 4326)::geography, {radius}, "
        f"timestamptz {q(starts)}, {('timestamptz ' + q(ends)) if ends else 'null'}, null, {q(source)}, {q(url)}, 'news')"
    )


for day in DATA["shutdowns"]:
    for a in day["areas"]:
        p = place(a["geo"])
        if not p:
            skipped.append(f"shutdown {day['date']} {a['name']}")
            continue
        when = "9 am to 2 pm" if day["timeStated"] else "Supply to resume before 2 pm; start time as usual for TNPDCL maintenance (9 am)"
        add("power_shutdown", f"TNPDCL ({a['name']} section)", f"Planned maintenance shutdown, {a['name']}",
            f"{a['list']}. {when}.", p, 1500,
            f"{day['date']} {day['from']}+05:30", f"{day['date']} {day['to']}+05:30", day["source"], day["url"])

for w in DATA["water"]:
    for zone, places in w["zones"].items():
        for entry in places:  # a name, or [name, alternative spellings...]
            names = entry if isinstance(entry, list) else [entry]
            name = names[0]
            p = place(names)
            if not p:
                skipped.append(f"water {name}")
                continue
            add("water_suspension", w["agency"], w["title"], f"{name} ({zone}). {w['note']}", p, 1200,
                w["starts"], w["ends"], w["source"], w["url"])

for i in DATA["incidents"]:
    p = [i["lat"], i["lng"]] if "lat" in i else place(i["geo"])
    if not p:
        skipped.append(f"incident {i['title']}")
        continue
    add(i["kind"], i["agency"], i["title"], i["area"], p, i["radius"], i["at"], None, i["source"], i["url"])

CACHE_FILE.write_text(json.dumps(cache, indent=1), encoding="utf-8")

values = ",\n".join(rows)
sql = f"""-- Theru real records: published shutdown notices, water suspensions and news reports, each with its source link.
-- Generated by scripts/build-real-seed.py from scripts/real-records.json. Re-runnable.
-- Locations are approximate: the centre of the named locality with a radius, placed with OpenStreetMap Nominatim.

-- Remove the synthetic demo layer (notices, demo power cuts) and previous real imports.
delete from public.notices where provenance in ('demo', 'news');
delete from public.clusters where kind = 'outage' and demo;

insert into public.notices (kind, agency, title, area_text, location, radius_m, starts_at, ends_at, reference, source_name, source_url, provenance) values
{values};
"""
(ROOT / "supabase" / "seed-real.sql").write_text(sql, encoding="utf-8")
print(f"{len(rows)} records written; skipped {len(skipped)}:", *skipped, sep="\n  ")
