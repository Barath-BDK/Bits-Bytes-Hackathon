"""Build supabase/seed-osm-works.sql: roads and rail lines mapped as under construction in OpenStreetMap, Chennai.

Each way is cut into stretches of about 800 m; each stretch becomes one 'works' notice (centre + radius), linked to
the OpenStreetMap way it came from. Run: python -I scripts/build-osm-works.py   (from the civic-app folder)
Data: (c) OpenStreetMap contributors, ODbL.
"""
import json, math, re, sys, urllib.parse, urllib.request
sys.stdout.reconfigure(encoding="utf-8")
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BBOX = "12.88,80.12,13.17,80.31"  # Greater Chennai Corporation area
QUERY = f"""[out:json][timeout:90];
(way["highway"="construction"]({BBOX}); way["railway"="construction"]({BBOX}););
out tags geom;"""

req = urllib.request.Request("https://overpass-api.de/api/interpreter", data=urllib.parse.urlencode({"data": QUERY}).encode(),
                             headers={"User-Agent": "theru-civic-hackathon/1.0"})
with urllib.request.urlopen(req, timeout=120) as r:
    ways = json.load(r)["elements"]

def km(a, b):
    return math.hypot((a[0] - b[0]) * 111.0, (a[1] - b[1]) * 111.0 * math.cos(math.radians(a[0])))

KIND_NAME = {"motorway": "Expressway", "motorway_link": "Expressway ramp", "trunk": "Highway", "primary": "Main road",
             "secondary": "Road", "tertiary": "Road", "residential": "Street", "service": "Service road", "subway": "Metro line",
             "rail": "Rail line", "light_rail": "Metro line"}

METRO = {"Yellow": "4"}  # CMRL Phase 2: the Yellow Line is corridor 4

def describe(t):
    what = t.get("construction") or ""
    is_rail = "railway" in t
    noun = KIND_NAME.get(what, "Metro line" if is_rail else "Road")
    raw = (t.get("name") or t.get("name:en") or "").replace("→", "to").replace("–", "-")
    name = re.sub(r"\s*\((u/c|proposed|underground\s*\d*|elevated)\)\s*", " ", raw, flags=re.I).strip()
    m = re.match(r"(?:Line\s*(\d+)|(Yellow) Line)\D*?(?::\s*(.+))?$", name)
    if is_rail and m:
        no = m.group(1) or METRO.get(m.group(2), "")
        route = (m.group(3) or "").strip()
        return f"Metro Line {no} under construction"[:200], "Chennai Metro Rail (CMRL)", f"Line {no}, {route}" if route else f"Line {no}"
    title = f"{name}: {noun.lower()} under construction" if name else f"{noun} under construction"
    agency = t.get("operator") or t.get("network") or ("Chennai Metro Rail (CMRL)" if is_rail and what in ("subway", "light_rail", "") else "")
    return title[:200], (agency or "Agency not recorded in OpenStreetMap")[:120], name

rows, now = [], datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M+00")
for w in ways:
    pts = [(p["lat"], p["lon"]) for p in w.get("geometry", [])]
    if len(pts) < 2:
        continue
    if "proposed" in (w.get("tags", {}).get("name") or "").lower():
        continue  # tagged as construction but named as a proposal: not shown as works in progress
    title, agency, name = describe(w.get("tags", {}))
    # walk the line and emit a stretch every ~800 m
    seg, acc = [pts[0]], 0.0
    stretches = []
    for a, b in zip(pts, pts[1:]):
        acc += km(a, b)
        seg.append(b)
        if acc >= 0.8:
            stretches.append(seg); seg, acc = [b], 0.0
    if len(seg) > 1 or not stretches:
        stretches.append(seg)
    for s in stretches:
        lat = sum(p[0] for p in s) / len(s); lng = sum(p[1] for p in s) / len(s)
        radius = max(80, min(500, int(max(km((lat, lng), p) for p in s) * 1000) + 40))
        rows.append((title, agency, name, round(lat, 5), round(lng, 5), radius, w["id"]))

# collapse stretches that land on top of each other (parallel carriageways, ramps, junctions); named ones win
kept = []
for r in sorted(rows, key=lambda r: (r[2] == "", -r[5])):
    if any(km((k[3], k[4]), (r[3], r[4])) < 0.6 for k in kept):
        continue
    kept.append(r)

labels = sorted({(t, a, (f"Along {n}" if n else "Mapped construction stretch")) for t, a, n, *_ in kept})
index = {l: i for i, l in enumerate(labels)}
# compact payload: a label table, then one [label, lat, lng, radius, way id] row per stretch
stretch_rows = [[index[(t, a, (f"Along {n}" if n else "Mapped construction stretch"))], lat, lng, rad, wid] for t, a, n, lat, lng, rad, wid in kept]
lab = json.dumps([list(l) for l in labels], ensure_ascii=False, separators=(",", ":")).replace("'", "''")
pts = json.dumps(stretch_rows, separators=(",", ":"))
sql = f"""-- Theru: construction mapped in OpenStreetMap (highway=construction, railway=construction), Chennai.
-- Generated by scripts/build-osm-works.py on {now}. Re-runnable. Data (c) OpenStreetMap contributors, ODbL.
-- starts_at is the import time: OpenStreetMap records that the works exist, not when they began.
delete from public.notices where provenance = 'osm';
with labels as (select ord - 1 as i, l->>0 as title, l->>1 as agency, l->>2 as area
                from json_array_elements('{lab}'::json) with ordinality as t(l, ord)),
     pts as (select (p->>0)::int as i, (p->>1)::float8 as lat, (p->>2)::float8 as lng, (p->>3)::int as r, p->>4 as way
             from json_array_elements('{pts}'::json) p)
insert into public.notices (kind, agency, title, area_text, location, radius_m, starts_at, source_name, source_url, provenance)
select 'works', l.agency, l.title, l.area, st_setsrid(st_makepoint(p.lng, p.lat), 4326)::geography, p.r,
       timestamptz '{now}', 'OpenStreetMap contributors', 'https://www.openstreetmap.org/way/' || p.way, 'osm'
from pts p join labels l using (i);
"""
(ROOT / "supabase" / "seed-osm-works.sql").write_text(sql, encoding="utf-8")
print(len(ways), "ways ->", len(rows), "stretches ->", len(kept), "notices")
from collections import Counter
print(Counter(k[0] for k in kept).most_common(15))
